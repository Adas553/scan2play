-- V1 — baseline: the schema as it was when Flyway was adopted (2026-09-28).
--
-- Taken from a schema-only dump of the working local database (which mirrors the manually
-- maintained production schema), so it matches the JPA entities under `entity/`.
--
--  * On a database that ALREADY has these tables, Flyway does NOT run this file: with
--    spring.flyway.baseline-on-migrate=true it records the existing schema as version 1
--    and only applies V2 and later. Compare a production schema dump with this file before
--    the first production deploy — Hibernate's ddl-auto=validate will refuse to start if
--    they differ.
--  * On an EMPTY database (fresh clone, CI, tests) this file creates the whole schema.
--
-- NEVER edit this file after it has been applied anywhere — add a new V<n>__<what>.sql.

-- ---------------------------------------------------------------------------
-- feedback
-- ---------------------------------------------------------------------------
CREATE TABLE public.feedback (
    id           bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    message      character varying(2000) NOT NULL,
    owner_id     character varying(255)  NOT NULL,
    party_code   character varying(5)    NOT NULL,
    submitted_at timestamp(6) without time zone,
    CONSTRAINT feedback_pkey PRIMARY KEY (id)
);

CREATE INDEX idx_feedback_owner_id     ON public.feedback USING btree (owner_id);
CREATE INDEX idx_feedback_submitted_at ON public.feedback USING btree (submitted_at);

-- ---------------------------------------------------------------------------
