    spotify_refresh_token    character varying(2048),
    spotify_token_expires_at timestamp(6) without time zone,
    fallback_playlist_url    character varying(500),
    fallback_shuffle         boolean DEFAULT true NOT NULL,
    CONSTRAINT party_settings_pkey PRIMARY KEY (id),
    CONSTRAINT ukat1ra56n8ttdykpqpypp8jnh4 UNIQUE (party_code),
