-- ---------------------------------------------------------------------------
-- song_requests
-- ---------------------------------------------------------------------------
CREATE TABLE public.song_requests (
    id           bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    decision     character varying(255),
    dj_comment   character varying(500),
    energy_level integer NOT NULL,
    party_code   character varying(5) NOT NULL,
    requested_at timestamp(6) without time zone,
    song_name    character varying(255),
    style        character varying(255),
    track_url    character varying(500),
    CONSTRAINT song_requests_pkey PRIMARY KEY (id)
);

CREATE INDEX idx_party_code          ON public.song_requests USING btree (party_code);
CREATE INDEX idx_party_decision_time ON public.song_requests USING btree (party_code, decision, requested_at DESC);

-- ---------------------------------------------------------------------------
-- youtube_cache — search query -> video ID (permanent IDs, 30-day TTL in code)
-- ---------------------------------------------------------------------------
CREATE TABLE public.youtube_cache (
    id           bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    created_at   timestamp(6) without time zone NOT NULL,
    search_query character varying(500) NOT NULL,
    video_id     character varying(20)  NOT NULL,
    CONSTRAINT youtube_cache_pkey PRIMARY KEY (id),
    CONSTRAINT idx_youtube_cache_query UNIQUE (search_query)
);
